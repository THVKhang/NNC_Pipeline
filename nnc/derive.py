"""A design whose RTL the flow generates, derived from a verified design (`nnc derive <src> <dst>`).

The experiment of the design half: take a design whose specification, rules (G1), contract (G2) and
verification (G3) exist and are approved, leave its RTL behind, let agent A15 write a new RTL from the
specification, and run the same approved verification (and the upstream hand-written testbench, when
`baseline/` exists) on it. Neither A15 nor the verification ever saw the other.

Copied: spec/ (documents and standards), work/rules.json, work/rules.md, work/contract.json,
work/contract.md, work/spec/ (indexes), verif/, run_set.json and baseline/ (with its NOTICE),
LICENSE/NOTICE files, and the design configuration with rtl_origin=generated. NOT copied: rtl/, bugs/ (its
one-line faults are written against the delivered RTL), results,
triage, mutation, formal results, logs and the answer cache.

Gate approvals G1-G3 are carried over only because their artifacts are byte-identical (the hashes are
checked again by `nnc status`); each carried record says where it came from. D1, D2 and G4 start open.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

from nnc.project import STATE_FILE, Design, ProjectError, _now

COPY_FILES = ("work/rules.json", "work/rules.md", "work/contract.json", "work/contract.md", "run_set.json",
              "LICENSE-Apache-2.0", "NOTICE.md")
COPY_DIRS = ("spec", "work/spec", "verif", "baseline")
CARRY = ("G1_rules", "G2_contract", "G3_verif_sources")


def derive(src_root: Path, dst_root: Path) -> Design:
    src = Design.open(src_root)
    if dst_root.exists() and any(dst_root.iterdir()):
        raise ProjectError(f"{dst_root} exists and is not empty")
    dst = Design.init(dst_root)
    for rel in COPY_DIRS:
        if (src.root / rel).is_dir():
            shutil.copytree(src.root / rel, dst.root / rel, dirs_exist_ok=True)
    for rel in COPY_FILES:
        if (src.root / rel).is_file():
            (dst.root / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src.root / rel, dst.root / rel)
    bl = dst.root / "baseline" / "baseline.json"
    if bl.is_file():                              # the generated RTL has its own file names
        desc = json.loads(bl.read_text(encoding="utf-8"))
        desc["rtl"] = "filelist"
        bl.write_text(json.dumps(desc, indent=1) + "\n", encoding="utf-8")
    sstate = json.loads((src.root / STATE_FILE).read_text(encoding="utf-8"))
    dstate = json.loads((dst.root / STATE_FILE).read_text(encoding="utf-8"))
    cfg = dict(sstate.get("config", {}))
    cfg["rtl_origin"] = "generated"
    cfg["derived_from"] = src.name
    dstate["config"] = cfg
    carried = {}
    for g in CARRY:
        rec = sstate.get("gates", {}).get(g)
        if rec:
            rec = dict(rec)
            rec["note"] = (f"[carried over from {src.name} at {_now()}: identical artifacts] " + rec.get("note", "")).strip()
            carried[g] = rec
    dstate["gates"] = carried
    (dst.root / STATE_FILE).write_text(json.dumps(dstate, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    nb = dst.root / "NOTICE.md"
    extra = (f"\n\n## Derived design\n\nThis workspace was derived from `designs/{src.name}` by `nnc derive`. The "
             "RTL in `rtl/` is NOT the upstream RTL: it was generated by agent A15 of the flow from the specification "
             "(see work/rtl_gen.md). The specification, the verification and the baseline testbench are those of "
             f"`designs/{src.name}`.\n")
    nb.write_text((nb.read_text(encoding="utf-8") if nb.is_file() else "# Notice\n") + extra, encoding="utf-8")
    return Design.open(dst.root)
