"""Adaptation of a new RTL to the flow, generated from the intake (no agent, no tokens).

Three things, each recorded in work/adapt.json and shown at Gate 1:
1. library files: the units the top needs from library folders (`--lib`) are copied unchanged into rtl/, and
   rtl/filelist.f gets the compile order of the intake;
2. a wrapper `<top>_nnc` when the top has struct or array ports: wiring only, no logic. Each field of a packed
   struct (or element of an array) becomes one port, so cocotb drives plain vectors. The wrapper checks at time 0
   in simulation that every DUT port still has the width it was generated for: a parameter set that changes a
   struct layout stops the run instead of truncating silently (simulation runs with -Wno-WIDTH);
3. an interface document spec/<top>_interface.md (document role `interface`): the port table of the verified
   top in the form of docs/SPEC_TEMPLATE.md section 5, from the port declarations and from the netlist
   (which inputs clock or reset flops). It says which field of which DUT port each port carries. It adds no
   behaviour: that comes only from the specification, so the extraction agents do not read this document.
"""
from __future__ import annotations

import hashlib
import json
import re
import shutil
from pathlib import Path

from nnc import intake

GENERATED = "Generated by NNC Pipeline (nnc adapt)"


def wrapper_name(top: str) -> str:
    return f"{top}_nnc"


def _leaf(port: str, path: str) -> str:
    s = re.sub(r"\[(\d+)\]", r"_\1", path).replace(".", "_")
    return f"{port}_{s.strip('_')}" if s else port


def wrapper_ports(ports: list[dict]) -> list[dict]:
    """Ports of the wrapper: [{name, direction, width, of: port, path, lsb, element}]."""
    out = []
    for p in ports:
        h = intake.port_handling(p)
        if h == "direct":
            out.append({"name": p["name"], "direction": p["direction"], "width": p["width"], "of": p["name"],
                        "path": "", "lsb": 0, "element": None})
        elif p["kind"] in ("struct", "packed_array", "clock_vector"):
            for path, lsb, w in p["fields"]:
                out.append({"name": _leaf(p["name"], path), "direction": p["direction"], "width": w,
                            "of": p["name"], "path": path, "lsb": lsb, "element": None})
        elif p["kind"] == "unpacked_array":
            lo, hi = min(p["range"]), max(p["range"])
            for k in range(lo, hi + 1):
                for path, lsb, w in (p["fields"] or [("", 0, p["width"])]):
                    out.append({"name": _leaf(p["name"], f"[{k}]" + ("." + path if path else "")),
                                "direction": p["direction"], "width": w, "of": p["name"], "path": path,
                                "lsb": lsb, "element": k})
        else:
            raise ValueError(f"port {p['name']}: {p['kind']} cannot be adapted")
    names = [w["name"] for w in out]
    dup = sorted({n for n in names if names.count(n) > 1})
    if dup:
        raise ValueError("flattened port names collide: " + ", ".join(dup))
    return out


def _w(width: int) -> str:
    return f"[{width - 1}:0] " if width > 1 else ""


def wrapper_sv(top: str, ports: list[dict], params: list[dict]) -> str:
    wtop = wrapper_name(top)
    wp = wrapper_ports(ports)
    ints = [p for p in params if intake.contract_param(p)]
    L = [f"// {wtop}: {GENERATED} from the port declarations of {top}. Do not edit: nnc adapt rewrites it.",
         f"// Wiring only, no logic: every struct or array port of {top} is split into one port per field, so a",
         "// cocotb test drives plain vectors. Port widths are those of the elaborated parameter values below; at time 0",
         "// the simulation stops if a DUT port has another width (a parameter set that changes a struct layout).",
         f"module {wtop}" + (" #(" if ints else " (")]
    if ints:
        L.append(",\n".join(f"  parameter {p['name']} = {p['value']}" for p in ints))
        L.append(") (")
    decl = []
    for q in wp:
        d = {"input": "input ", "output": "output", "inout": "inout "}[q["direction"]]
        kind = "wire " if q["direction"] == "inout" else "logic"
        decl.append(f"  {d} {kind} {_w(q['width'])}{q['name']}")
    L.append(",\n".join(decl))
    L.append(");")
    conns = []
    body = []
    checks = []
    for p in ports:
        if intake.port_handling(p) == "direct":
            conns.append(f".{p['name']}({p['name']})")
            continue
        flat = f"nnc_{p['name']}"
        mine = [q for q in wp if q["of"] == p["name"]]
        if p["kind"] == "unpacked_array":
            r = p["range"]
            body.append(f"  logic {_w(p['width'])}{flat} [{r[0]}:{r[1]}];")
            for q in mine:
                tgt = f"{flat}[{q['element']}]" + (f"[{q['lsb'] + q['width'] - 1}:{q['lsb']}]" if p["fields"] else "")
                body.append(f"  assign {tgt} = {q['name']};" if p["direction"] == "input"
                            else f"  assign {q['name']} = {tgt};")
            checks.append((p["name"], f"$bits(u_dut.{p['name']}[{r[0]}])", p["width"]))
        else:
            body.append(f"  logic {_w(p['width'])}{flat};")
            for q in mine:
                sl = f"{flat}[{q['lsb'] + q['width'] - 1}:{q['lsb']}]"
                body.append(f"  assign {sl} = {q['name']};  // {p['name']}.{q['path']}" if p["direction"] == "input"
                            else f"  assign {q['name']} = {sl};  // {p['name']}.{q['path']}")
            checks.append((p["name"], f"$bits(u_dut.{p['name']})", p["width"]))
        conns.append(f".{p['name']}({flat})")
    L += body
    pmap = ", ".join(f".{p['name']}({p['name']})" for p in ints)
    L.append(f"  {top}" + (f" #({pmap})" if ints else "") + " u_dut (\n    " + ",\n    ".join(conns) + "\n  );")
    if checks:
        L.append("`ifndef SYNTHESIS")
        L.append("  initial begin")
        for name, expr, w in checks:
            L.append(f"    if ({expr} != {w}) $fatal(1, \"{wtop}: port {name} of {top} has %0d bits, the wrapper was "
                     f"generated for {w}: run nnc adapt for this parameter set\", {expr});")
        L.append("  end")
        L.append("`endif")
    L.append("endmodule")
    return "\n".join(L) + "\n"


def _signal_type(name: str, struct: dict | None) -> str:
    s = struct or {}
    if name in (s.get("clocks") or {}):
        edges = s["clocks"][name]["edges"]
        return "Clock" + ("" if edges == ["rise"] else f" ({'/'.join(edges)} edge)")
    for key, kind in (("async_resets", "asynchronous"), ("sync_resets", "synchronous")):
        if name in (s.get(key) or {}):
            act = s[key][name]["active"]
            return f"Reset ({kind}, active {'/'.join(act)})"
    return "Data"


def _kept_why(p: dict) -> str:
    if p.get("enum"):
        return "an enum"
    if not isinstance(p.get("value"), int):
        return "not a number"
    return f"{p.get('width')} bits" if (p.get("width") or 0) > 32 else "outside the 32-bit range"


def interface_md(top: str, verified_top: str, ports: list[dict], params: list[dict], struct: dict | None,
                 spec_name: str | None) -> str:
    wp = wrapper_ports(ports) if verified_top != top else [
        {"name": p["name"], "direction": p["direction"], "width": p["width"], "of": p["name"], "path": "",
         "lsb": 0, "element": None} for p in ports]
    by_port = {p["name"]: p for p in ports}
    s_clocks = (struct or {}).get("clocks") or {}
    clock_of: dict[str, list[str]] = {}         # port of the verified top -> edges of the flops it clocks
    for q in wp:
        src = by_port[q["of"]]
        if q["of"] == q["name"] and q["name"] in s_clocks:
            clock_of[q["name"]] = s_clocks[q["name"]]["edges"]
        elif src["kind"] == "clock_vector" and q["lsb"] in (src.get("clock_lanes") or []):
            clock_of[q["name"]] = s_clocks[src["name"]]["edges"]
    clocks = list(clock_of)
    single = len(clocks) == 1
    L = [f"# {verified_top}: interface for verification", "",
         f"{GENERATED} from the port declarations of `{top}` and from its netlist (which inputs clock or reset "
         f"flops). Do not edit by hand: nnc adapt rewrites it.", "",
         f"This document gives only the ports of the design under verification `{verified_top}` and which part of "
         f"which port of `{top}` each one carries. The behaviour of `{top}` is specified only by "
         + (f"`{spec_name}`" if spec_name else "its specification") + "; nothing here adds to it.", ""]
    if verified_top != top:
        L += [f"`{verified_top}` is a wrapper of wiring only: each field of a struct port, and each element of an "
              f"array port, of `{top}` is a separate port here. A port named `<port>_<field>` carries field "
              f"`<field>` of port `<port>` of `{top}`.", ""]
    ints = [p for p in params if intake.contract_param(p)]
    kept = [p for p in params if not intake.contract_param(p)]
    if ints or kept:
        L += ["## 1 Parameters", ""]
    if ints:
        L += ["| Parameter | Default | Legal values | Description |", "|---|---|---|---|"]
        L += [f"| {p['name']} | {p['value']} | Not given | Parameter of `{top}`; the legal values are those of its "
              f"specification |" for p in ints]
        L.append("")
    if kept:
        L += [f"These parameters of `{top}` keep the default of the RTL and are not set by the verification: "
              + ", ".join(f"`{p['name']}` ({_kept_why(p)})" for p in kept)
              + ". The contract carries 32-bit integer parameters only.", ""]
    L += ["## 2 Interface", "", f"**`{verified_top}`**: all ports" + (f" (`{clocks[0].upper()}`)" if single else ""),
          "", "| Port | Direction | Width | Signal type | Reset value | Clock domain | Meaning |",
          "|---|---|---|---|---|---|---|"]
    for q in wp:
        src = by_port[q["of"]]
        if q["name"] in clock_of:
            edges = clock_of[q["name"]]
            typ = "Clock" + ("" if edges == ["rise"] else f" ({'/'.join(edges)} edge)")
        else:
            typ = _signal_type(q["name"], struct) if q["of"] == q["name"] else "Data"
        if q["name"] in clocks:
            dom = q["name"].upper()
        else:
            dom = clocks[0].upper() if single else "See specification"
        if q["of"] == q["name"]:
            meaning = f"port `{q['of']}` of `{top}`"
        elif q["element"] is not None:
            meaning = (f"element {q['element']}" + (f", field `{q['path']}`," if q["path"] else "") +
                       f" of port `{q['of']}` of `{top}`")
        elif src["kind"] == "clock_vector":
            meaning = f"bit {q['lsb']} (from the LSB) of port `{q['of']}` of `{top}`"
        else:
            meaning = f"field `{q['path'].lstrip('.')}` of port `{q['of']}` of `{top}`"
        if src.get("type") and src["kind"] not in ("vector", "clock_vector"):
            meaning += f" (type `{src['type']}`)"
        reset = "Not applicable" if typ != "Data" or q["direction"] == "input" else "See specification"
        L.append(f"| {q['name']} | {q['direction']} | {q['width']} | {typ} | {reset} | {dom} | {meaning} |")
    L.append("")
    return "\n".join(L)


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def adapt(root: Path, rep: dict, *, spec_name: str | None, write: bool = True, interface: bool = False) -> dict:
    """Write the adaptation of the design at `root` from its intake report `rep` (`interface`: write the
    interface document even when the specification has a port table)."""
    if rep["verdict"] in ("needs_input", "unsupported"):
        raise ValueError(f"intake verdict {rep['verdict']}: " +
                         "; ".join(r["message"] for r in rep["reasons"] if r["level"] in ("needs_input", "unsupported")))
    col = rep["collect"]
    top = col["top"]
    rtl = root / "rtl"
    out: dict = {"top": top, "copied": [], "wrapper": None, "interface": None, "verified_top": top}
    # 1. library files and the headers they include, flat into rtl/
    names: dict[str, Path] = {}
    for f in [Path(x) for x in col["files"]]:
        if f.parent.resolve() != rtl.resolve():
            if f.name in names and names[f.name] != f:
                raise ValueError(f"two library files named {f.name}: {names[f.name]} and {f}")
            names[f.name] = f
    for d in [Path(x) for x in col.get("include_dirs") or []]:
        if d.resolve() == rtl.resolve():
            continue
        for h in d.iterdir():
            if h.is_file() and h.suffix.lower() in intake.HDR_EXT and h.name not in names:
                names[h.name] = h
    for name, src in sorted(names.items()):
        dst = rtl / name
        if dst.exists() and _sha(dst) != _sha(src):
            raise ValueError(f"rtl/{name} exists and differs from library file {src}")
        out["copied"].append({"file": f"rtl/{name}", "from": str(src), "sha256": _sha(src)})
        if write and not dst.exists():
            shutil.copyfile(src, dst)
    order = [Path(x).name for x in col["files"]]
    # 2. the wrapper
    needs = any(intake.port_handling(p) == "adapter" for p in rep["ports"])
    if needs:
        wtop = wrapper_name(top)
        text = wrapper_sv(top, rep["ports"], rep["parameters"])
        out["wrapper"] = {"file": f"rtl/{wtop}.sv", "module": wtop, "ports": len(wrapper_ports(rep["ports"])),
                          "adapted": [p["name"] for p in rep["ports"] if intake.port_handling(p) == "adapter"]}
        out["verified_top"] = wtop
        order.append(f"{wtop}.sv")
        if write:
            (rtl / f"{wtop}.sv").write_text(text, encoding="utf-8", newline="\n")
    out["filelist"] = order
    if write:
        (rtl / "filelist.f").write_text(f"// {GENERATED}: compile order of the intake\n" + "\n".join(order) + "\n",
                                        encoding="utf-8", newline="\n")
    # 3. the interface document, when the specification has no port table the flow reads, or with a wrapper
    spec_errors = [f for f in (rep.get("spec") or {}).get("findings", []) if f["severity"] == "error"]
    if needs or spec_errors or interface or rep.get("spec") is None:
        vt = out["verified_top"]
        name = f"spec/{vt}_interface.md"
        out["interface"] = name
        if write:
            (root / name).write_text(interface_md(top, vt, rep["ports"], rep["parameters"], rep.get("structure"),
                                                  spec_name), encoding="utf-8", newline="\n")
    if write:
        (root / "work").mkdir(exist_ok=True)
        (root / "work" / "adapt.json").write_text(
            json.dumps(intake.portable(out, root, Path.cwd()), indent=1) + "\n", encoding="utf-8")
        (root / "work" / "adapt.md").write_text(to_markdown(out), encoding="utf-8")
    return out


def to_markdown(a: dict) -> str:
    L = ["# Adaptation", "", f"{GENERATED}. Review at Gate 1: none of it changes the behaviour of `{a['top']}`.", "",
         f"- verified top: `{a['verified_top']}`"]
    if a["wrapper"]:
        w = a["wrapper"]
        L.append(f"- wrapper `{w['file']}`: {w['ports']} ports; flattened: " + ", ".join(f"`{x}`" for x in w["adapted"]))
    if a["interface"]:
        L.append(f"- interface document `{a['interface']}` (role interface: contract port table, not extracted)")
    if a["copied"]:
        L += ["", "Library files copied unchanged into rtl/:", "", "| File | From | SHA-256 |", "|---|---|---|"]
        L += [f"| {c['file']} | {c['from']} | {c['sha256'][:16]} |" for c in a["copied"]]
    L += ["", "Compile order (rtl/filelist.f): " + ", ".join(a["filelist"])]
    return "\n".join(L) + "\n"
